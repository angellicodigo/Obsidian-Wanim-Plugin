import esbuild from "esbuild";
import process from "process";
import fs from "node:fs";
import { builtinModules } from "node:module";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Obsidian Wanim Plugin - In-browser Manim with Python
*/
`;

const prod = process.argv[2] === "production";

// Expand Node builtins to include 'node:' prefix and wildcards
const nodeBuiltins = [
	...builtinModules,
	...builtinModules.map((m) => `node:${m}`),
	"node:*",
];

// esbuild plugin to inline browser/rapydscript.js as text for synchronous in-memory bootstrap
const rapydscriptAsTextPlugin = {
	name: "wanim-rapydscript-loader",
	setup(build) {
		build.onLoad({ filter: /[/\\]rapydscript\.js$/ }, async (args) => {
			const contents = await fs.promises.readFile(args.path, "utf8");
			return {
				contents,
				loader: "text",
			};
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...nodeBuiltins,
	],
	format: "cjs",
	platform: "browser",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	define: {
		"import.meta.url": JSON.stringify("http://localhost/"),
	},
	plugins: [rapydscriptAsTextPlugin],
});

if (prod) {
	await context.rebuild();
	await context.dispose();
	process.exit(0);
} else {
	await context.watch();
}
